#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ADDRESS_PATTERN = /^0x[a-fA-F0-9]{40}$/;

const networkName = process.argv[2];

if (!networkName) {
  console.error("Usage: node scripts/generate-deployment-artifacts.mjs <network>");
  process.exit(1);
}

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = process.env.REPO_ROOT
  ? path.resolve(process.env.REPO_ROOT)
  : path.resolve(scriptDir, "..");
const deploymentPath = path.join(repoRoot, "deployments", `${networkName}.json`);

let deployment;
try {
  deployment = JSON.parse(readFileSync(deploymentPath, "utf8"));
} catch (error) {
  console.error(`Missing or invalid deployment JSON for "${networkName}": ${deploymentPath}`);
  console.error(`Deploy first with: DEPLOY_CONTRACTS=1 make base-sepolia`);
  process.exit(1);
}

const fail = (message) => {
  console.error(`${deploymentPath}: ${message}`);
  process.exit(1);
};

if (deployment.schemaVersion !== 1) {
  fail(`unsupported schemaVersion ${deployment.schemaVersion}`);
}

if (deployment.network !== networkName) {
  fail(`network field "${deployment.network}" does not match requested "${networkName}"`);
}

if (typeof deployment.deployNetwork !== "string" || deployment.deployNetwork.length === 0) {
  fail("deployNetwork must be set");
}

if (typeof deployment.deploymentProfile !== "string" || deployment.deploymentProfile.length === 0) {
  fail("deploymentProfile must be set");
}

if (!ADDRESS_PATTERN.test(deployment.registryAddress)) {
  fail("registryAddress must be a 20-byte hex address");
}

if (
  typeof deployment.deploymentBlockNumber !== "number" ||
  !Number.isSafeInteger(deployment.deploymentBlockNumber) ||
  deployment.deploymentBlockNumber < 0
) {
  fail("deploymentBlockNumber must be a non-negative safe integer");
}

if (!deployment.forums || typeof deployment.forums !== "object" || Array.isArray(deployment.forums)) {
  fail("forums must be an object mapping forum names to addresses");
}

const forumOrder = Array.isArray(deployment.forumOrder)
  ? deployment.forumOrder
  : Object.keys(deployment.forums);

if (forumOrder.length === 0) {
  fail("forumOrder must contain at least one forum");
}

for (const forumName of forumOrder) {
  const address = deployment.forums[forumName];
  if (!ADDRESS_PATTERN.test(address)) {
    fail(`forums.${forumName} must be a 20-byte hex address`);
  }
}

const orderedForumAddresses = forumOrder.map((forumName) => deployment.forums[forumName]);
const relayAllowedContracts = [...orderedForumAddresses, deployment.registryAddress];
const registryMode = deployment.registryMode ?? "production";
const registrySponsorshipSignatures =
  registryMode === "dev"
    ? ["register(string)"]
    : ["register((bytes32,(bytes32,bytes,bytes32[]),bytes,(uint256,string,string,bool)))"];
const registryContractLabel =
  registryMode === "dev"
    ? "DevSymvoliaRegistry"
    : registryMode === "mock"
      ? "MockSymvoliaRegistry"
      : "SymvoliaRegistry";
const label =
  networkName === "localhost"
    ? "the local Hardhat development network (chain 31337)"
    : registryMode === "production"
      ? `the ${networkName} network`
      : `the ${networkName} network with ${registryContractLabel}`;

const networksDir = path.join(repoRoot, "frontend/src/contracts/networks");
mkdirSync(networksDir, { recursive: true });

const networksModuleText =
  "/**\n" +
  ` * Contract addresses for ${label}.\n` +
  " * Auto-generated by `scripts/generate-deployment-artifacts.mjs` -- do not edit manually.\n" +
  " */\n\n" +
  `export const FORUMS = ${JSON.stringify(deployment.forums, null, 2)} as const;\n\n` +
  `export const REGISTRY_ADDRESS = "${deployment.registryAddress}" as const;\n`;

const networkModulePath = path.join(networksDir, `${networkName}.ts`);
writeFileSync(networkModulePath, networksModuleText);
console.log(`Wrote frontend network config to ${networkModulePath}`);

const backendGeneratedDir = path.join(repoRoot, "backend/.generated");
mkdirSync(backendGeneratedDir, { recursive: true });

const backendEnvText =
  "# Auto-generated by scripts/generate-deployment-artifacts.mjs -- do not edit manually.\n" +
  `DEPLOY_NETWORK=${deployment.deployNetwork}\n` +
  `DEPLOYMENT_PROFILE=${deployment.deploymentProfile}\n` +
  `REGISTRY_MODE=${registryMode}\n` +
  `REGISTRY_ADDRESS=${deployment.registryAddress}\n` +
  `GAS_SPONSORSHIP_REGISTRY_SIGNATURES="${registrySponsorshipSignatures.join(";")}"\n` +
  `DEPLOYMENT_BLOCK_NUMBER=${deployment.deploymentBlockNumber}\n` +
  `FORUM_CONTRACT_ADDRESSES="${orderedForumAddresses.join(",")}"\n` +
  `RPC_RELAY_ALLOWED_CONTRACTS="${relayAllowedContracts.join(",")}"\n`;

const backendEnvPath = path.join(backendGeneratedDir, "deployment.env");
writeFileSync(backendEnvPath, backendEnvText);
console.log(`Wrote backend deployment env to ${backendEnvPath}`);
