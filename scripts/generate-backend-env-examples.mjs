#!/usr/bin/env node
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import {
  backendServiceConfig,
  deploymentsDir,
  loadDeployment,
  profileIndexerEnabled,
  registrySponsorshipSignatures,
  repoRoot,
} from "./lib/backend-config.mjs";

const outputDir = path.join(repoRoot, "deploy/env");

const backendEnvText = (networkName, deployment, forumOrder) => {
  const registryMode = deployment.registryMode ?? "production";
  const indexerEnabled = profileIndexerEnabled(deployment.deploymentProfile);
  const orderedForumAddresses = forumOrder.map((forumName) => deployment.forums[forumName]);
  const relayAllowedContracts = [...orderedForumAddresses, deployment.registryAddress];
  const signatures = registrySponsorshipSignatures(registryMode);

  // Non-secret service settings from the committed backend-services config.
  // Fall back to placeholders when a network has no entry yet.
  const service = backendServiceConfig(networkName) ?? {};
  const corsOrigins =
    typeof service.corsOrigins === "string" && service.corsOrigins.length > 0
      ? service.corsOrigins
      : "https://replace-with-your-frontend-origin";
  const inspectApprove = service.gasSponsorshipInspectApprove === true ? "true" : "false";

  // INDEXER_ENABLED defaults to true in the backend, so only emit it when the
  // profile opts out (the non-default case worth calling out explicitly).
  const indexerToggleLines = indexerEnabled
    ? ""
    : `# Indexing is disabled for this profile: the search API and RPC relay remain
# available while the Meilisearch index stays empty (no chain polling).
INDEXER_ENABLED=false
`;


  const verifierLines =
    registryMode === "production"
      ? `# Required in production registry mode: the verifier is eth_call'd to recover
# a registration's zkPassport id (verify() is simulated, not executed).
ZKPASSPORT_VERIFIER_ADDRESS=${service.zkPassportVerifierAddress ?? "0xREPLACE_WITH_ZKPASSPORT_VERIFIER_ADDRESS"}`
      : `# ZKPASSPORT_VERIFIER_ADDRESS is only needed in production registry mode;
# ${registryMode} registrations are metered without an RPC verify() call.`;

  return `# Symvolia backend environment example for ${networkName}.
# Generated by scripts/generate-backend-env-examples.mjs from deployments/${networkName}.json.
# Copy these values into your backend service and replace placeholder values.

# Contract deployment metadata
DEPLOY_NETWORK=${deployment.deployNetwork}
DEPLOYMENT_PROFILE=${deployment.deploymentProfile}
REGISTRY_MODE=${registryMode}
REGISTRY_ADDRESS=${deployment.registryAddress}
GAS_SPONSORSHIP_REGISTRY_SIGNATURES="${signatures.join(";")}"
FORUM_CONTRACT_ADDRESSES="${orderedForumAddresses.join(",")}"

# Chain RPC endpoints
# INDEXER_RPC_URL is required for pull-based log polling.
INDEXER_RPC_URL=https://replace-with-your-http-rpc
# RELAY_RPC_URL is used by the RPC relay for frontend read traffic.
# Use a dedicated Alchemy/Infura app here to separate frontend from indexer quota.
RELAY_RPC_URL=https://replace-with-your-frontend-http-rpc

# Indexer polling and catch-up behavior
${indexerToggleLines}INDEXER_POLL_INTERVAL_SECONDS=60
INDEXER_MAX_BLOCKS_PER_REQUEST=600
INDEXER_MAX_STARTUP_LOOKBACK_SECONDS=14400

# Optional constrained JSON-RPC relay for frontend read traffic.
# Keep methods limited to what the frontend actually uses.
# eth_getLogs powers the optional browser-local search engine.
RPC_RELAY_ALLOWED_METHODS=eth_chainId,eth_blockNumber,eth_getBlockByNumber,eth_getTransactionByHash,eth_getTransactionReceipt,eth_call,eth_estimateGas,eth_getCode,eth_getLogs
# Include forum contracts plus the registry contract for frontend reads.
RPC_RELAY_ALLOWED_CONTRACTS="${relayAllowedContracts.join(",")}" 
RPC_RELAY_UPSTREAM_TIMEOUT_SECONDS=15
# eth_getLogs requests must start on a multiple of this many blocks and span at
# most this many blocks. A fixed window keeps historical queries canonical (so
# the upstream RPC can cache them) and bounds each request. Must match the
# frontend local-search GETLOGS_WINDOW_BLOCKS (1000).
RPC_RELAY_GETLOGS_WINDOW_BLOCKS=1000

# Gas sponsorship webhook (Alchemy Gas Manager)
# Approve inspection requests from the Gas Manager webhook policy. Sourced from
# deploy/backend-services.json; off fails closed (users self-fund instead).
ALCHEMY_GAS_SPONSORSHIP_INSPECT_APPROVE=${inspectApprove}
# Off-chain per-human leaky-bucket rate limiter for gas-sponsored actions.
# Set GAS_SPONSORSHIP_RATE_LIMIT_DB to a path on a persistent Railway Volume to
# enable metering; leave it unset to sponsor purely by function selector.
# The bucket is denominated in gas: each sponsored userOperation costs the sum of
# its gas-limit fields, charged against the sender's zkPassport human identity.
# On Railway: add a Volume to this service (mount path e.g. /data), then set:
GAS_SPONSORSHIP_RATE_LIMIT_DB=/data/sponsorship.db
GAS_SPONSORSHIP_RATE_LIMIT_CAPACITY_GAS=5000000
GAS_SPONSORSHIP_RATE_LIMIT_LEAK_GAS_PER_DAY=20000000
# RPC used to resolve a userOperation's zkPassport id (getUserIdentifier /
# verify). Falls back to INDEXER_RPC_URL when unset.
GAS_SPONSORSHIP_RPC_URL=https://replace-with-your-http-rpc
${verifierLines}

# Meilisearch connection
# For Railway private networking, use: http://<meilisearch-service-name>.railway.internal:7700
MEILI_URL=http://meilisearch.railway.internal:7700
MEILI_API_KEY=replace-with-meili-master-key

# Browser/API access (from deploy/backend-services.json)
CORS_ORIGINS=${corsOrigins}

# Optional semantic similarity search. Start with false for first deploys;
# enable once Meilisearch is healthy and backed by persistent storage.
MEILI_SEMANTIC_SEARCH_ENABLED=false
MEILI_SEMANTIC_EMBEDDER_NAME=statement-text
MEILI_SEMANTIC_EMBEDDER_MODEL=sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2
MEILI_TASK_TIMEOUT_MS=300000
`;
};

const meilisearchEnvText = `# Symvolia Meilisearch Railway environment example.
# Copy these values into each Railway Meilisearch service.

# Railway uses PORT to choose the internal healthcheck target port.
PORT=7700

# Use development for non-production environments and production for production.
MEILI_ENV=production

# Generate a distinct strong value per environment, for example:
#   openssl rand -hex 32
MEILI_MASTER_KEY=replace-with-generated-master-key
`;

mkdirSync(outputDir, { recursive: true });

const networkNames = readdirSync(deploymentsDir)
  .filter((fileName) => fileName.endsWith(".json"))
  .map((fileName) => path.basename(fileName, ".json"))
  .filter((networkName) => networkName !== "localhost")
  .sort();

try {
  for (const networkName of networkNames) {
    const { deployment, forumOrder } = loadDeployment(networkName);
    const outputPath = path.join(outputDir, `${networkName}.backend.env.example`);
    writeFileSync(outputPath, backendEnvText(networkName, deployment, forumOrder));
    console.log(`Wrote ${outputPath}`);
  }
} catch (error) {
  console.error(error.message);
  process.exit(1);
}

const meilisearchOutputPath = path.join(outputDir, "railway-meilisearch.env.example");
writeFileSync(meilisearchOutputPath, meilisearchEnvText);
console.log(`Wrote ${meilisearchOutputPath}`);